// The AME2012 nuclear mass table, and G4NucleiProperties::GetNuclearMass on top of it.
//
// Transcribed from G4NucleiPropertiesTableAME12 (source/particles/management, 11.1.1): the
// `indexArray[0]` list of Z, the `shortTable` index into it by A, and the `MassExcess` values
// in keV. The A row of `indexArray` is not transcribed - it is implied by `shortTable`, whose
// contract is that entries `shortTable[A-1] .. shortTable[A]-1` are exactly the nuclides with
// that A - and `BetaEnergy` is not needed by anything here.
//
// WHY A CROSS-SECTION PACKAGE CARRIES A MASS TABLE
//
// Two Coulomb barriers need the target nucleus's mass and nothing else will do:
//
//   G4NuclearRadii::CoulombFactor(Z, A, particle, ekin)   - the below-14-MeV branch of
//       G4BGGNucleonElasticXS / G4BGGNucleonInelasticXS and the below-20-MeV branch of
//       G4BGGPionElasticXS / G4BGGPionInelasticXS
//   G4ComponentGGNuclNuclXsc::ComputeCoulombBarier         - every ion-ion cross section
//
// Both build the centre-of-mass kinetic energy from `sqrt(pM^2 + tM^2 + 2*pElab*tM)` with
// `tM = G4NucleiProperties::GetNuclearMass(A, Z)`, and both return exactly zero when that
// energy is below the barrier. A mass that is wrong by a per cent moves the threshold, and
// below the threshold the cross section is not approximately right, it is zero or it is not.
//
// docs/HADRONIC_PLAN.md gives G4NucleiProperties to P3 (de-excitation), which needs binding
// energies, mass excesses, the theoretical tables and the Cameron formula. This file is the
// subset the cross sections need and no more: the AME12 measured table, the six light nuclei
// Geant4 answers from the particle table instead, and a loud refusal for everything else.
//
// WHAT IS REFUSED, BY NAME
//
// G4NucleiProperties::GetNuclearMass falls through four levels. The first two are here; the
// last two are not, and `nuclear_mass_known` reports which:
//
//   1. Z <= 2 and one of (1,1) (0,1) (1,2) (1,3) (2,4) (2,3) -> the PDG mass of proton,
//      neutron, deuteron, triton, alpha, He3. Note these are *particle* masses, not the AME
//      table's values for the same nuclides, and they differ: AME gives 938.7830 MeV for the
//      proton's atomic mass less its electron, CLHEP's proton_mass_c2 is 938.272013.
//   2. G4NucleiPropertiesTableAME12 - measured, 3353 nuclides, A <= 273, Z <= 110.
//   3. G4NucleiPropertiesTheoreticalTable - NOT PORTED. 2772 lines of calculated masses for
//      nuclides with no measurement. Nothing a QBBC target can be reaches it: the targets are
//      Geant4's elements, whose isotopes are the naturally occurring ones.
//   4. G4NucleiProperties::NuclearMass, the Cameron/Weizsaecker formula, and the Z==A and
//      Z==0 shortcuts above it - NOT PORTED, same reason.
//
// A caller that lands in 3 or 4 gets zero from `nuclear_mass` and false from
// `nuclear_mass_known`, and the cross-section wrappers turn that into a refusal rather than
// into a Coulomb barrier computed from a zero mass - which would be a barrier of zero, i.e.
// silently no barrier at all.
