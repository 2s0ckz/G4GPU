/// The most final states one channel can have at one multiplicity, over all 34 tables: 96, in
/// G4CascadeKminusPChannel's multiplicity-7 block. `sigmaBuf` is a std::vector in Geant4 and a
/// fixed array here, so the bound is asserted rather than assumed - `kMaxChannelsPerMult` is
/// checked against the generated table in tests/test_bertini_data.cu.
constexpr int kMaxChannelsPerMult = 96;

/// The most particles one final state can have: 9.
constexpr int kMaxFinalStateSize = 9;

enum class ChannelRefusal {
  kNone = 0,
  kNoTable,                        ///< GetTable returned null for this initial state
  kSingleChannelAboveMult2,        ///< see note 2 in the header - the mu- p out-of-bounds read
  kMultiplicityAboveMax,           ///< getOutgoingParticleTypes' own "Illegal multiplicity"
  kBufferTooSmall                  ///< kMaxChannelsPerMult exceeded; never in 11.1.1's data
};

// =============================================================================================
// A channel table, as a view over the generated data
// =============================================================================================

/// Which of the three arrays a caller is asking `find_cross_section` for. Only NN, NP and PP
/// care, and they care because their override identifies its two special arrays by CONTENT.
enum class XsArray { kTot = 0, kSum, kInelastic, kMultiplicity, kChannel };

struct ChannelTable {
  const data::BertiniChannel* def = nullptr;
  int slot = -1;                     ///< index into data::bertini_channels(), so that the host
                                     ///< can find the name in kBertiniChannelNames
  const double* bins = nullptr;
  const double* xs = nullptr;        ///< [nxs][ne] for this channel
  const double* tot = nullptr;       ///< [ne], or `sum` when the channel has no measured total
  const double* mult = nullptr;      ///< [n_mult][ne]
  const double* sum = nullptr;       ///< [ne]
  const double* inelastic = nullptr; ///< [ne]
  const signed char* fs[8] = {nullptr, nullptr, nullptr, nullptr,
                              nullptr, nullptr, nullptr, nullptr};
  bool has_measured_total = false;   ///< `&data.sum != &data.tot`
  bool stepanov = false;             ///< NN, NP or PP: the 0-10 MeV closed form
  double stepanov_a = 0.0;           ///< the numerator of the 1/ke term
  double stepanov_b = 0.0;
  double stepanov_c = 0.0;
  double stepanov_num = 0.0;         ///< 1.92 for NP, 4.0 for NN and PP
  __host__ __device__ bool valid() const { return def != nullptr; }
  __host__ __device__ int ne() const { return def->ne; }
  __host__ __device__ int n_mult() const { return def->n_mult; }
  __host__ __device__ int max_multiplicity() const { return def->n_mult + 1; }
};

/// G4CascadeChannelTables::GetTable(initialState). A linear scan of 34 entries, which is what
/// Geant4's std::map lookup amounts to and is cheaper on a device than any tree.
__host__ __device__ inline ChannelTable channel_table(int initial_state) {
  ChannelTable t;
  const data::BertiniChannel* all = data::bertini_channels();
  for (int i = 0; i < data::kBertiniChannels; ++i) {
    if (all[i].initial_state != initial_state) { continue; }
    const data::BertiniChannel& d = all[i];
    t.def = &d;
    t.slot = i;
    t.bins = (d.sampler == 0) ? data::bertini_bins_pionnuc()
           : (d.sampler == 1) ? data::bertini_bins_kaon()
                              : data::bertini_bins_kaonhyp();
    t.xs = data::bertini_channel_xs() + d.xs_off;
    const double* dv = data::bertini_channel_derived() + d.deriv_off;
    t.mult = dv;
    t.sum = dv + d.n_mult * d.ne;
    t.inelastic = t.sum + d.ne;
    t.has_measured_total = (d.tot_off >= 0);
    t.tot = t.has_measured_total ? (data::bertini_channel_tot() + d.tot_off) : t.sum;
    for (int m = 0; m < 8; ++m) {
      t.fs[m] = (d.fs_off[m] >= 0) ? (data::bertini_channel_fs() + d.fs_off[m]) : nullptr;
    }
    // The three nucleon-nucleon channels override findCrossSection below 10 MeV. The constants
    // are per channel: NP uses (3.0885, 0.0011748, 5.3107) with 1.92, NN and PP use
    // (9.0692, 0.0050574, 6.9466) with 4.0 - which are G4InuclSpecialFunctions::csPN's and
    // csNN's low-energy coefficients written a second time, in different units.
    if (initial_state == kNeutron * kProton) {
      t.stepanov = true;
      t.stepanov_a = 3.0885; t.stepanov_b = 0.0011748; t.stepanov_c = 5.3107;
      t.stepanov_num = 1.92;
    } else if (initial_state == kNeutron * kNeutron || initial_state == kProton * kProton) {
      t.stepanov = true;
      t.stepanov_a = 9.0692; t.stepanov_b = 0.0050574; t.stepanov_c = 6.9466;
      t.stepanov_num = 4.0;
    }
    return t;
  }
  return t;   // def == nullptr: no table, which is what FindTable's map miss returns
}

/// G4CascadeSampler::findCrossSection, including the NN/NP/PP override.
///
/// `which` says which array is being read, because the override's `std::equal` test is a
/// content comparison against `tot` and against `crossSections[0]` - and `crossSections[0]` is
/// the elastic channel's row for all three of these tables (their multiplicity-2 block has one
/// entry, `{pro,neu}` / `{neu,neu}` / `{pro,pro}`, and it is the elastic one). So the two arrays
/// the override fires for are exactly "the total" and "the elastic channel", and a caller always
/// knows which of those it is asking for.
__host__ __device__ inline double find_cross_section(const ChannelTable& t, double ke,
                                                     XsArray which, int chan_index = -1) {
  if (t.stepanov && ke < 0.01) {
    const bool is_elastic_row = (which == XsArray::kChannel && chan_index == t.def->elastic_chan);
    if (which == XsArray::kTot || is_elastic_row) {
      const double kemin = t.stepanov_num / t.tot[0];
      if (ke > 0.001) { return (t.stepanov_a - t.stepanov_b / ke) / ke + t.stepanov_c; }
      if (ke > kemin) { return t.stepanov_num / ke; }
      return t.tot[0];
    }
  }
  const double* y = nullptr;
  switch (which) {
    case XsArray::kTot: y = t.tot; break;
    case XsArray::kSum: y = t.sum; break;
    case XsArray::kInelastic: y = t.inelastic; break;
    case XsArray::kMultiplicity: y = t.mult + chan_index * t.def->ne; break;
    case XsArray::kChannel: y = t.xs + chan_index * t.def->ne; break;
  }
  return interp_value(ke, t.bins, y, t.def->ne);
}

/// G4CascadeFunctions::getCrossSection - the inclusive total.
__host__ __device__ inline double channel_cross_section(const ChannelTable& t, double ke) {
  return find_cross_section(t, ke, XsArray::kTot);
}

/// G4CascadeFunctions::getCrossSectionSum - the sum of the exclusive channels.
///
/// Note that for NN, NP and PP below 10 MeV this does NOT get Stepanov's form: `sum` is neither
// `tot` nor `crossSections[0]`, so `std::equal` fails on both and the base interpolator runs.
/// The two therefore disagree by a large factor there (the tabulated `tot[0]` is 20360 mb for NP
/// against a summed 20360 as well, but at 5 MeV the closed form gives 613 mb against the table's
/// linear interpolation between 20360 and 302) - and `getMultiplicity` divides one by the other.
__host__ __device__ inline double channel_cross_section_sum(const ChannelTable& t, double ke) {
  return find_cross_section(t, ke, XsArray::kSum);
}

/// G4CascadeSampler::sampleFlat over a filled buffer. Returns the index, and sets `fell_off`
/// when the cumulative walk ran past the end - the branch Geant4's own comment questions.
__host__ __device__ inline int sample_flat(const double* sigma, int n, double u,
                                          bool& fell_off) {
  fell_off = false;
  if (n <= 1) { return 0; }
  double fsum = 0.0;
  for (int i = 0; i < n; ++i) { fsum += sigma[i]; }
  fsum *= u;
  double partial = 0.0;
  for (int i = 0; i < n; ++i) {
    partial += sigma[i];
    if (fsum < partial) { return i; }
  }
  fell_off = true;
  return 0;
}

/// G4CascadeFunctions::getMultiplicity.
///
/// Two deviates or one, depending on the channel: the summed/total comparison is only made when
/// the table carries a measured inclusive cross section, and `findMultiplicity` itself draws one
/// only when the buffer has more than one entry - which it always does here, since every channel
/// has at least six multiplicities.
template <typename Rng>
__host__ __device__ inline int channel_multiplicity(const ChannelTable& t, double ke, Rng& rng,
                                                    bool& fell_off) {
  fell_off = false;
  if (t.has_measured_total) {
    const double summed = find_cross_section(t, ke, XsArray::kSum);
    const double total = find_cross_section(t, ke, XsArray::kTot);
    if (rng.uniform() > summed / total) { return t.max_multiplicity(); }
  }
  double buf[8];
  const int nm = t.def->n_mult;
  const double pos = interp_get_bin(ke, t.bins, t.def->ne);
  for (int im = 0; im < nm; ++im) {
    buf[im] = interp_apply(pos, t.mult + im * t.def->ne, t.def->ne);
  }
  return sample_flat(buf, nm, rng.uniform(), fell_off) + 2;
}

/// G4CascadeSampler::findFinalStateIndex + G4CascadeFunctions::getOutgoingParticleTypes.
///
/// Writes `mult` type codes into `kinds` and returns the refusal, if any. The
/// `stop - start <= 1` arm is where Geant4 mixes an absolute index into a per-multiplicity
/// array; this refuses instead, for the one channel where the two differ (see note 2).
/// `sigma_buf` must have room for `kMaxChannelsPerMult` doubles and comes from the caller's
/// workspace, not from this function's stack.
///
/// That is not style. Written with a local `double buf[96]`, this function gave
/// `bertini_tables_probe` a **992-byte stack frame** under `-Xptxas -v`; with the buffer passed
/// in it is 224 bytes. A cascade at 5 GeV has hundreds of particles in flight and every one of
/// them calls this, so 768 bytes of per-thread local memory is 768 bytes of L1 that the nucleus
/// model's tables wanted - and `sigmaBuf` is a `std::vector` data member in Geant4 for the same
/// reason, reused across calls rather than reallocated.
template <typename Rng>
__host__ __device__ inline ChannelRefusal outgoing_particle_types(
    const ChannelTable& t, int mult, double ke, Rng& rng, int* kinds, int& out_channel,
    bool& fell_off, double* sigma_buf) {
  fell_off = false;
  out_channel = -1;
  if (!t.valid()) { return ChannelRefusal::kNoTable; }
  const int max_mult = t.max_multiplicity();
  if (mult > max_mult) {
    // Geant4 prints " Illegal multiplicity" and CLAMPS to the maximum rather than failing, so
    // the clamp is reproduced and the refusal is reported alongside it: the caller gets a
    // usable final state and a flag saying its multiplicity was not the one requested.
    mult = max_mult;
  }
  if (mult < 2) { return ChannelRefusal::kMultiplicityAboveMax; }

  const int start = t.def->index[mult - 2];
  const int stop = t.def->index[mult - 1];
  int channel;
  if (stop - start <= 1) {
    if (start != 0) { return ChannelRefusal::kSingleChannelAboveMult2; }
    channel = start;
  } else {
    if (stop - start > kMaxChannelsPerMult) { return ChannelRefusal::kBufferTooSmall; }
    const double pos = interp_get_bin(ke, t.bins, t.def->ne);
    for (int i = start; i < stop; ++i) {
      sigma_buf[i - start] = interp_apply(pos, t.xs + i * t.def->ne, t.def->ne);
    }
    channel = sample_flat(sigma_buf, stop - start, rng.uniform(), fell_off);
  }

  const signed char* block = t.fs[mult - 2];
  if (block == nullptr) { return ChannelRefusal::kMultiplicityAboveMax; }
  for (int j = 0; j < mult; ++j) { kinds[j] = block[channel * mult + j]; }
  out_channel = channel;
  return ChannelRefusal::kNone;
}

