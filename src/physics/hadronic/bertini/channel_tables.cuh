// G4CascadeChannelTables and everything under it: the 34 two-body channel tables Bertini's
// colliders look every cross section, multiplicity and final state up in.
//
// Transcribed from Geant4 11.1.1:
//   G4CascadeChannelTables::GetTable / FindTable  (cascade/cascade/src/G4CascadeChannelTables.cc)
//   G4CascadeFunctions::getCrossSection / getCrossSectionSum / getMultiplicity /
//     getOutgoingParticleTypes                    (cascade/cascade/include/G4CascadeFunctions.icc)
//   G4CascadeSampler::findCrossSection / findMultiplicity / findFinalStateIndex /
//     fillSigmaBuffer / sampleFlat                (cascade/cascade/include/G4CascadeSampler.icc)
//   G4CascadeInterpolator::getBin / interpolate   (cascade/cascade/include/G4CascadeInterpolator.icc)
//   G4CascadeData::initialize                     (cascade/cascade/include/G4CascadeData.icc)
//   G4CascadeNNChannel / G4CascadeNPChannel / G4CascadePPChannel::findCrossSection
//                                                 (their own .cc files)
//   G4PionNucSampler / G4KaonSampler / G4KaonHypSampler  (their .cc files: the bin edges)
//
// The data is `src/data/bertini_channels.hh`, generated by
// `tools/extract_bertini_channels.pl`: 185,970 cross sections, 42,890 final-state codes and the
// 9,472 values G4CascadeData::initialize derives from them. This file is the code that reads it.
//
// ---------------------------------------------------------------------------------------------
// Four things about these tables that a reading of the class does not show.
//
// **1. `getCrossSection` and `getCrossSectionSum` are different numbers for eight channels and
// the same number for twenty-six.** `getCrossSection` interpolates `tot`, `getCrossSectionSum`
// interpolates `sum`, and `tot` IS `sum` - the same array, by reference - unless the channel's
// constructor was given a measured inclusive array. Eight were: gamma-N, the three pion-nucleon
// pairs, NN, NP, PP and mu-p. For those the measured total is LARGER than the sum of the
// exclusive channels, and `getMultiplicity` uses the shortfall:
//
//     if (&data.sum != &data.tot) {
//       if (G4UniformRand() > summed/total) return data.maxMultiplicity();
//     }
//
// so a fraction `1 - sum/tot` of collisions are forced to the highest multiplicity the table
// has, and the other twenty-six channels never take that branch **and never draw that deviate**.
// The random stream therefore depends on which constructor a channel used. `tot_off < 0` in the
// generated table is what records it.
//
// **2. `findFinalStateIndex` returns an ABSOLUTE index on one path and a RELATIVE one on the
// other.** Its body is
//
//     G4int start = index[mult-2], stop = index[mult-1];
//     if (stop-start <= 1) return start;          // absolute
//     fillSigmaBuffer(ke, xsec, start, stop);
//     return sampleFlat();                        // relative, 0..(stop-start-1)
//
// and `getOutgoingParticleTypes` then indexes the PER-MULTIPLICITY array `xMbfs[channel]` with
// the result. The two agree only when `start == 0`, which is multiplicity 2 and nothing else. Any
// channel with exactly one final state at a multiplicity above 2 reads out of bounds, and in
// 11.1.1 exactly one does: G4CascadeMuMinusPChannel is `G4CascadeData<30,1,1,1,1,1,1,1,1>`.
// `outgoing_particle_types` below returns `ChannelRefusal::kSingleChannelAboveMult2` for it
// rather than reproducing the out-of-bounds read. docs/RISK.md V119.
//
// **3. `sampleFlat` returns 0 when the cumulative walk falls off the end**, with Geant4's own
// question mark beside it ("Is this right? Shouldn't it return maximum, not minimum?"). It is
// reachable: `fsum = total * u` and then `if (fsum < partialSum) return i` - at u very close to 1
// the accumulated partial sum can round just below `fsum` and the loop exits. Reproduced, not
// corrected, and the branch is counted so a test can see it fire.
//
// **4. NN, NP and PP replace the whole 0-10 MeV bin with a closed form, and they select it by
// comparing ARRAY CONTENTS.** The override is
//
//     if (ke < 0.01 && (std::equal(xsec, xsec+30, npTotXSec) ||
//                       std::equal(xsec, xsec+30, npCrossSections[0])))
//
// - not a pointer comparison. So it fires for `tot` and for the elastic channel's own row, and
// it would fire for any other array that happened to hold the same 30 values. Below 10 MeV those
// two lookups return Stepanov's function and every other lookup on the same channel returns the
// interpolated table. `stepanov_kind` below carries which of the two arrays is being asked for,
// because the caller knows and a content comparison on the device would be 30 loads per lookup.
#ifndef G4GPU_BERTINI_CHANNEL_TABLES_CUH
#define G4GPU_BERTINI_CHANNEL_TABLES_CUH

#include <cmath>

#include "data/bertini_channels.hh"
#include "physics/hadronic/bertini/cascade_interpolator.cuh"
#include "physics/hadronic/bertini/inucl_particle.cuh"

