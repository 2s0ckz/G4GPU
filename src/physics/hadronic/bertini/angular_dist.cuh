/// The CDF inversion. Two things are worth spelling out because both look like bugs and are not:
///
///   * the uniform is drawn BEFORE the energy branch, so the number of deviates is one either
///     way and the random stream does not depend on which arm ran;
///   * `Interpolate` loops `for j in 1..nDists` and `break`s on the first `ekin < labKE[j]`,
///     leaving `angDist` untouched if no j satisfies it. That cannot happen here because the
///     caller already tested `ekin < labKE[nDists-1]`, but the buffer is a MUTABLE MEMBER in
///     Geant4, so a failed interpolation would sample the previous call's distribution. Here the
///     buffer is a local and the guard is explicit.
///
/// Above the last tabulated energy the table is abandoned for
/// `costh = log(1 - u(1 - exp(2s)))/s - 1` with `s = 2*tcoeff*pcm^2`, which is an exponential in
/// t. Note `s` grows with pcm^2, so at a few GeV/c the distribution is extremely forward and the
/// logarithm's argument is `1 - u` to within rounding.
template <typename Rng>
__host__ __device__ inline double numint_cos_theta(const data::BertiniNumIntAngDst& d,
                                                   double ekin, double pcm, Rng& rng) {
  const double* base = data::bertini_numint_data();
  const double* ke = base + d.ke_off;
  const double* cosb = base + d.cos_off;
  const double* tab = base + d.tab_off;
  double costh = 1.0;
  double slope = 1.0;
  const double xrand = rng.uniform();
  if (ekin < ke[d.nke - 1]) {
    // Interpolate() between the bracketing energies.
    double dist[19];              // kMaxAngleBins; every table in 11.1.1 has 19
    bool filled = false;
    for (int j = 1; j < d.nke; ++j) {
      if (ekin >= ke[j]) { continue; }
      const double frac = (ekin - ke[j - 1]) / (ke[j] - ke[j - 1]);
      for (int i = 0; i < d.nang; ++i) {
        dist[i] = (1.0 - frac) * tab[(j - 1) * d.nang + i] +
                  frac * tab[j * d.nang + i];
      }
      filled = true;
      break;
    }
    if (!filled) { return 1.0; }   // unreachable under the caller's own test; see above
    for (int i = 1; i < d.nang; ++i) {
      if (xrand < dist[i]) {
        slope = (cosb[i] - cosb[i - 1]) / (dist[i] - dist[i - 1]);
        costh = (xrand - dist[i - 1]) * slope + cosb[i - 1];
        break;
      }
    }
  } else {
    slope = 2.0 * d.tcoeff * pcm * pcm;
    costh = std::log(1.0 - xrand * (1.0 - std::exp(2.0 * slope))) /
            slope - 1.0;
  }
  return costh;
}

