// G4TwoBodyAngularDist, G4MultiBodyMomentumDist and the nineteen distribution objects they
// dispatch to.
//
// Transcribed from Geant4 11.1.1:
//   G4TwoBodyAngularDist::ChooseDist         (cascade/cascade/src/G4TwoBodyAngularDist.cc)
//   G4MultiBodyMomentumDist::ChooseDist      (cascade/cascade/src/G4MultiBodyMomentumDist.cc)
//   G4NumIntTwoBodyAngDst::GetCosTheta / Interpolate
//                                            (cascade/cascade/include/G4NumIntTwoBodyAngDst.icc)
//   G4ParamExpTwoBodyAngDst::GetCosTheta     (cascade/cascade/include/G4ParamExpTwoBodyAngDst.icc)
//   G4InuclParamAngDst::GetCosTheta          (cascade/cascade/src/G4InuclParamAngDst.cc)
//   G4InuclParamMomDst::GetMomentum          (cascade/cascade/src/G4InuclParamMomDst.cc)
//
// The tables are `src/data/bertini_angdst.hh`, generated by
// `tools/extract_bertini_angdst.pl`. This file is the code that samples them.
//
// ---------------------------------------------------------------------------------------------
// **ChooseDist's first test has nothing to do with angles.** Its opening lines are
//
//     if (fs==0 && kw==0) {
//       if (is == pro*pro || is == pro*neu || is == neu*neu) return nn3BodyDst;
//       else return hn3BodyDst;
//     }
//
// under a comment reading "TEMPORARY: Three-body distributions for hN/NN". A final state of 0
// is the sentinel G4CascadeFinalStateAlgorithm passes when it wants a THREE-BODY distribution
// rather than a two-body one, and the two objects it returns take `(ptype, ekin)` rather than
// `(ekin, pcm)` - a different signature reached through the same virtual. So the dispatcher has
// two return types in one function, and the caller has to know which it got. `choose_two_body`
// below returns a tagged union for that reason, rather than a pointer.
//
// **The order of the tests is the specification.** `is == pro*pro || is == neu*neu` returns the
// PP distribution before the hyperon block is reached, and `fs == is` gates the three elastic
// pion tests - so pi+p -> pi+p gets G4PipP2PipPAngDst while pi+p -> anything else falls through
// to the `kw == 2` strangeness test and then to the two hadron-nucleon elastic tables. Any
// reordering changes which table a reaction reads, and `ref/oracle/bertini_angchoice.csv` pins
// the whole map: every (is, fs, kw) the colliders can ask for, against the name of the object
// Geant4 returned.
//
// **The nn (NuclNucl) object is the HYPERON-nucleon distribution, not the neutron-neutron one.**
// It is constructed as `nnAngDst(new G4NuclNuclAngDst)` and returned only from the hyperon
// block; neutron-neutron elastic scattering gets `ppAngDst` (G4PP2PPAngDst) through
// `is == pro*pro || is == neu*neu`. The member name is the trap.
