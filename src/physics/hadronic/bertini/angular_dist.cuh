/// Four interpolations, a small/large angle choice, then an inverted exponential.
///
/// The interpolator here is G4CascadeInterpolator with extrapolation ON, so an energy above the
/// last bin extrapolates the parameters linearly rather than clamping - and `pCos` and `pFrac`
/// are then clamped to their physical ranges afterwards, which is what makes the extrapolation
/// safe. `pA` and `pC` are NOT clamped, so a high-energy extrapolation can hand `term1` either
/// sign; the two guards below (`|term1| < 1e-7` and `term1 > DBL_MAX_EXP`) are Geant4's.
///
/// `DBL_MAX_EXP` is 1024, an *exponent*, compared against `term1`, a slope - comparing a value
/// against an exponent bound is a units error in Geant4, and it is reproduced because it is what
/// runs. The guard it was meant to be would have been `term1 > 709` (log(DBL_MAX)); at 1024 the
/// `G4Exp(-2*term1)` below is already exactly 0 and the arithmetic degrades gracefully, so the
/// error changes nothing. Recorded rather than corrected.
template <typename Rng>
__host__ __device__ inline double paramexp_cos_theta(const data::BertiniParamExpAngDst& d,
                                                     double ekin, double pcm, Rng& rng) {
  const double* base = data::bertini_paramexp_data();
  const double pos = interp_get_bin(ekin, base + d.ke_off, d.nke);
  double pA = interp_apply(pos, base + d.a_off, d.nke);
  double pC = interp_apply(pos, base + d.c_off, d.nke);
  double pCos = interp_apply(pos, base + d.cos_off, d.nke);
  double pFrac = interp_apply(pos, base + d.frac_off, d.nke);
  pCos = (pCos > 1.0) ? 1.0 : (pCos < -1.0) ? -1.0 : pCos;
  pFrac = (pFrac > 1.0) ? 1.0 : (pFrac < 0.0) ? 0.0 : pFrac;

  const bool small_angle = (rng.uniform() < pFrac);
  const double term1 = 2.0 * pcm * pcm * (small_angle ? pA : pC);
  if (std::fabs(term1) < 1e-7) { return 1.0; }
  if (term1 > 1024.0) { return 1.0; }          // DBL_MAX_EXP, as written
  const double term2 = std::exp(-2.0 * term1);
  const double rand_scale =
      (std::exp(-term1 * (1.0 - pCos)) - term2) / (1.0 - term2);
  const double u = rng.uniform();
  const double rand_val = small_angle ? ((1.0 - rand_scale) * u + rand_scale)
                                      : (rand_scale * u);
  return 1.0 + std::log(rand_val * (1.0 - term2) + term2) / term1;
}

