/// G4InuclParamAngDst::GetCosTheta(ptype, ekin). A rejection loop around
/// `randomInuclPowers` until the result lands in [0, 1], up to 100 tries, and then a FLAT
/// distribution if it never does - Geant4's comment says "Parametrizations aren't properly
/// bounded", and the flat fallback is reached for real at high energy.
///
/// `J` selects the coefficient block by whether the OUTGOING particle is a nucleon, so `ptype`
/// is the ejectile's type, not the projectile's.
template <typename Rng>
__host__ __device__ inline double paramang_cos_theta(const data::BertiniParamAngDst& d,
                                                     int ptype, double ekin, Rng& rng,
                                                     bool& used_flat) {
  const int J = (ptype == kProton || ptype == kNeutron) ? 0 : 1;
  const double* ab = data::bertini_paramang_data() + d.ab_off;
  double coeff[4][4];
  for (int i = 0; i < 4; ++i) {
    for (int k = 0; k < 4; ++k) { coeff[i][k] = ab[J * 16 + i * 4 + k]; }
  }
  const int itry_max = 100;
  double spow = -999.0;
  int itry = 0;
  while ((spow < 0.0 || spow > 1.0) && itry < itry_max) {
    ++itry;
    spow = inucl_random_powers(ekin, coeff, rng);
  }
  used_flat = (itry == itry_max);
  if (used_flat) { spow = rng.uniform(); }
  return 2.0 * spow - 1.0;
}

/// G4InuclParamMomDst::GetMomentum(ptype, ekin). One `randomInuclPowers` and a quadratic in
/// ekin, multiplied; `fabs` at the end because the product can come out negative.
///
/// There is NO rejection loop here, unlike the angular form - so `Spow` is used whatever it is,
/// including outside [0, 1], and `sqrt(S)*(PR + (1-PQ)S^4)` can be anything. That asymmetry
/// between the two classes is in Geant4 and it is why the momentum generator needs no
/// `used_flat`.
template <typename Rng>
__host__ __device__ inline double parammom_momentum(const data::BertiniParamMomDst& d,
                                                    int ptype, double ekin, Rng& rng) {
  const int JK = (ptype == kProton || ptype == kNeutron) ? 0 : 1;
  const double* pq = data::bertini_parammom_data() + d.pqpr_off;
  const double* ps_c = data::bertini_parammom_data() + d.ps_off;
  double coeff[4][4];
  for (int i = 0; i < 4; ++i) {
    for (int k = 0; k < 4; ++k) { coeff[i][k] = pq[JK * 16 + i * 4 + k]; }
  }
  const double spow = inucl_random_powers(ekin, coeff, rng);
  double ps = 0.0;
  for (int im = 0; im < 3; ++im) {
    ps += ps_c[JK * 3 + im] * g4pow_n(ekin, im);

  }
  return std::fabs(ps * spow);
}

