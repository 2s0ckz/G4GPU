/// Which family a chosen distribution belongs to, because the two families have different
/// sampling signatures and G4TwoBodyAngularDist returns both through one pointer.
enum class AngDstKind { kNone = 0, kNumInt, kParamExp, kParamAng3Body };

/// The index order in `data::bertini_numint_angdst()`, which is the order the extractor walks
/// the source files in. Named so that the dispatcher below reads like G4TwoBodyAngularDist's
/// constructor.
enum NumIntIndex {
  kNiGamP2NPip = 0, kNiGamP2PPi0, kNiNP2NP, kNiPP2PP,
  kNiPi0P2Pi0P, kNiPimP2Pi0N, kNiPimP2PimP, kNiPipP2PipP
};
enum ParamExpIndex { kPeGammaNucl = 0, kPeHadNElastic1, kPeHadNElastic2, kPeNuclNucl,
                     kPePiNInelastic };
enum ParamAngIndex { kPaHadNucl3Body = 0, kPaNuclNucl3Body };
enum ParamMomIndex { kPmHadNucl3Body = 0, kPmHadNucl4Body, kPmNuclNucl3Body, kPmNuclNucl4Body };

struct AngDstChoice {
  AngDstKind kind = AngDstKind::kNone;
  int index = -1;
};

/// G4TwoBodyAngularDist::ChooseDist(is, fs, kw), test for test and in order.
__host__ __device__ inline AngDstChoice choose_two_body_angdst(int is, int fs, int kw) {
  AngDstChoice c;
  // TEMPORARY (Geant4's word): the three-body distributions, reached with fs == 0 && kw == 0.
  if (fs == 0 && kw == 0) {
    c.kind = AngDstKind::kParamAng3Body;
    c.index = (is == kProton * kProton || is == kProton * kNeutron ||
               is == kNeutron * kNeutron) ? kPaNuclNucl3Body : kPaHadNucl3Body;
    return c;
  }
  // gamma-nucleon -> nucleon pi0
  if ((is == kPhoton * kProton && fs == kProton * kPionZero) ||
      (is == kPhoton * kNeutron && fs == kNeutron * kPionZero)) {
    c.kind = AngDstKind::kNumInt; c.index = kNiGamP2PPi0; return c;
  }
  // gamma-nucleon charge exchange
  if ((is == kPhoton * kProton && fs == kNeutron * kPionPlus) ||
      (is == kPhoton * kNeutron && fs == kProton * kPionMinus)) {
    c.kind = AngDstKind::kNumInt; c.index = kNiGamP2NPip; return c;
  }
  // pp and nn elastic - and NOTE this is G4PP2PPAngDst for BOTH, not the "nn" member
  if (is == kProton * kProton || is == kNeutron * kNeutron) {
    c.kind = AngDstKind::kNumInt; c.index = kNiPP2PP; return c;
  }
  // np and pn elastic
  if (is == kProton * kNeutron) { c.kind = AngDstKind::kNumInt; c.index = kNiNP2NP; return c; }
  // pi+ p and pi- n elastic
  if (fs == is && (is == kPionPlus * kProton || is == kPionMinus * kNeutron)) {
    c.kind = AngDstKind::kNumInt; c.index = kNiPipP2PipP; return c;
  }
  // pi- p and pi+ n elastic
  if (fs == is && (is == kPionMinus * kProton || is == kPionPlus * kNeutron)) {
    c.kind = AngDstKind::kNumInt; c.index = kNiPimP2PimP; return c;
  }
  // pi0 p and pi0 n elastic
  if (fs == is && (is == kPionZero * kProton || is == kPionZero * kNeutron)) {
    c.kind = AngDstKind::kNumInt; c.index = kNiPi0P2Pi0P; return c;
  }
  // the four pion charge exchanges
  if ((is == kPionMinus * kProton && fs == kPionZero * kNeutron) ||
      (is == kPionPlus * kNeutron && fs == kPionZero * kProton) ||
      (is == kPionZero * kProton && fs == kPionPlus * kNeutron) ||
      (is == kPionZero * kNeutron && fs == kPionMinus * kProton)) {
    c.kind = AngDstKind::kNumInt; c.index = kNiPimP2Pi0N; return c;
  }
  // hyperon-nucleon: this is where G4NuclNuclAngDst is used
  if (is == kProton * kLambda || is == kProton * kSigmaPlus || is == kProton * kSigmaZero ||
      is == kProton * kSigmaMinus || is == kProton * kXiZero || is == kProton * kXiMinus ||
      is == kProton * kOmegaMinus ||
      is == kNeutron * kLambda || is == kNeutron * kSigmaPlus || is == kNeutron * kSigmaZero ||
      is == kNeutron * kSigmaMinus || is == kNeutron * kXiZero || is == kNeutron * kXiMinus ||
      is == kNeutron * kOmegaMinus) {
    c.kind = AngDstKind::kParamExp; c.index = kPeNuclNucl; return c;
  }
  // gamma p -> K Y and isospin variants
  if (kw == 2 && (is == kProton * kPhoton || is == kNeutron * kPhoton)) {
    c.kind = AngDstKind::kParamExp; c.index = kPeGammaNucl; return c;
  }
  // pion-nucleon strangeness production
  if (kw == 2) { c.kind = AngDstKind::kParamExp; c.index = kPePiNInelastic; return c; }
  // gamma p, K+ p, K0bar p, gamma n, K- n, K0 n
  if (is == kProton * kPhoton || is == kProton * kKaonPlus || is == kProton * kKaonZeroBar ||
      is == kNeutron * kPhoton || is == kNeutron * kKaonMinus || is == kNeutron * kKaonZero) {
    c.kind = AngDstKind::kParamExp; c.index = kPeHadNElastic1; return c;
  }
  // K- p, K0bar n, K+ n, K0 p
  if (is == kProton * kKaonMinus || is == kProton * kKaonZero ||
      is == kNeutron * kKaonPlus || is == kNeutron * kKaonZeroBar) {
    c.kind = AngDstKind::kParamExp; c.index = kPeHadNElastic2; return c;
  }
  return c;   // ChooseDist returns 0: an invalid interaction
}

/// G4MultiBodyMomentumDist::ChooseDist(is, mult). The `use3BodyMom` branch is the one Vladimir
/// Uzhinsky's 2011 comment says was removed, kept behind the flag: with the dumped default
/// (false) a three-body final state gets the FOUR-body generator, which is why the four-body
/// tables carry the whole multiplicity range.
__host__ __device__ inline int choose_multibody_momdst(int is, int mult,
                                                       const CascadeParams& par) {
  const bool nn = (is == kProton * kProton || is == kProton * kNeutron ||
                   is == kNeutron * kNeutron);
  if (nn) {
    if (par.use_3body_mom && mult == 3) { return kPmNuclNucl3Body; }
    return kPmNuclNucl4Body;
  }
  if (par.use_3body_mom && mult == 3) { return kPmHadNucl3Body; }
  return kPmHadNucl4Body;
}

